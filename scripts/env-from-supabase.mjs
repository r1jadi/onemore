#!/usr/bin/env node
/**
 * Prints (or writes) the `.env.local` values for a locally running Supabase
 * stack, using this repository's variable names.
 *
 * `supabase status -o env` is the authority: it prints the project URL, the
 * publishable key and the secret key for the containers on this machine. This
 * script only renames those values to the names in `.env.example`, so nobody has
 * to copy a key by hand.
 *
 *   node scripts/env-from-supabase.mjs                    # show the values (secret masked)
 *   node scripts/env-from-supabase.mjs --write            # create .env.local
 *   node scripts/env-from-supabase.mjs --from-file out.txt # parse captured status output (tests)
 *
 * Requires the Supabase CLI and a running stack (`npx supabase start`).
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(root, ".env.local");

/** Local status keys → this repository's names. First match wins. */
const MAPPING = [
  ["api_url", "VITE_SUPABASE_URL", "public", "Project URL"],
  ["api_url", "SUPABASE_URL", "public", "Project URL"],
  ["publishable_key", "VITE_SUPABASE_PUBLISHABLE_KEY", "public", "Publishable key"],
  ["anon_key", "VITE_SUPABASE_PUBLISHABLE_KEY", "legacy", "Legacy anon key (CLI < 2.45)"],
  ["secret_key", "SUPABASE_SECRET_KEY", "secret", "Secret key"],
  ["service_role_key", "SUPABASE_SECRET_KEY", "legacy", "Legacy service_role key (CLI < 2.45)"],
];

function parseArg(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : (process.argv[index + 1] ?? null);
}

function statusOutput() {
  const fromFile = parseArg("--from-file");
  if (fromFile) return readFileSync(resolve(root, fromFile), "utf8");
  try {
    return execFileSync("npx", ["--yes", "supabase", "status", "-o", "env"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
  } catch (error) {
    const detail = (error.stderr ?? "").toString().trim().split("\n").at(-1) ?? "";
    console.error("Could not read the local Supabase status.");
    console.error("Start the stack first:  npx supabase start");
    console.error(`CLI said: ${detail || error.message}`);
    process.exit(1);
  }
}

/** `KEY="value"` lines, split only on the first `=` (JWT values contain padding). */
function parseStatus(raw) {
  const values = new Map();
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const separator = trimmed.indexOf("=");
    if (separator === -1) continue;
    const key = trimmed.slice(0, separator).trim().toLowerCase();
    const value = trimmed
      .slice(separator + 1)
      .trim()
      .replace(/^["']|["']$/g, "");
    if (value) values.set(key, value);
  }
  return values;
}

function mask(value) {
  return value.length <= 12 ? "•••" : `${value.slice(0, 12)}…${value.slice(-4)}`;
}

function main() {
  const status = parseStatus(statusOutput());
  const rows = [];
  for (const [statusKey, name, kind, description] of MAPPING) {
    const value = status.get(statusKey);
    if (value && !rows.some((row) => row.name === name)) {
      rows.push({ name, value, kind, description });
    }
  }

  if (!rows.length) {
    console.error("The status output contained no keys this repository recognises.");
    console.error(`Looked for: ${[...new Set(MAPPING.map(([key]) => key))].join(", ")}`);
    process.exit(1);
  }

  const legacy = rows.filter((row) => row.kind === "legacy");
  if (legacy.length) {
    console.warn(
      "This Supabase CLI is older than 2.45 and printed legacy keys. They still work, " +
        "but Supabase deprecates them — update the CLI and use the publishable/secret pair.",
    );
  }

  const lines = [
    "# Generated by scripts/env-from-supabase.mjs from `supabase status -o env`.",
    "# Local development only. This file is gitignored.",
    "",
  ];
  for (const row of rows) {
    lines.push(`# ${row.description}${row.kind === "legacy" ? " — deprecated name" : ""}`);
    lines.push(`${row.name}=${row.value}`);
  }

  const write = process.argv.includes("--write");
  if (!write) {
    for (const row of rows) {
      const shown = row.kind === "public" ? row.value : mask(row.value);
      console.log(`${row.name}=${shown}`);
    }
    console.log("\nSecret values are masked. Re-run with --write to create .env.local.");
    return;
  }

  if (existsSync(OUTPUT) && !process.argv.includes("--force")) {
    console.error(".env.local already exists. Re-run with --force to overwrite it.");
    process.exit(1);
  }
  writeFileSync(OUTPUT, `${lines.join("\n")}\n`, "utf8");
  console.log(`Wrote ${OUTPUT} (${rows.length} values). Set the rest from .env.example.`);
}

main();
